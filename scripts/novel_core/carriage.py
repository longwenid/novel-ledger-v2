"""Dependency-derived revision scope: carry chapters the detectors cannot fault.

A revision branch used to redo the whole positional suffix (start..through):
every downstream chapter was re-drafted and re-reviewed even when the fix
never touched it (session e354 redid ch2-7 for two ch2/ch3 findings; session
14006c71 re-drafted ch3-10 for one leftover Latin word, and the re-drafts'
own drift became the next review's findings — a self-feeding loop).

The revision's findings define its scope: chapters they name are re-executed,
everything else is carried verbatim unless a detector refuses. An empty
delta (expression-level fix, no ledger change) now CARRIES too — the
measured alternative was worse: the suffix fell back to worker dispatch,
creative re-writes drifted (a carried-verbatim chapter cannot drift), and
each drift fed the next revision chain.

P3 honest capability — read this before trusting a carry. Carry decides "this
chapter is unaffected" by structural means, and structure cannot prove a
semantic claim. It is a conservative filter, not a proof, and it is blind in
exactly the direction of what prose can do that keys cannot:

  * a value reached only through free text whose owning entity the chapter
    never names (指代、称谓、"那把柴刀") — this one now has a channel: the
    writer can declare the coordinate in `reads`, and a declared read always
    refuses the carry. Without a declaration the blind spot stands;
  * a surface form the sweep does not enumerate (paraphrase, dropped unit,
    a number spelled in a way `_value_forms` does not generate);
  * on an empty delta, a downstream chapter that PARAPHRASES the changed
    wording. The echo sweep below catches the literal echo (another chapter
    still containing the removed wording — the measured multi-site glyph
    case); a paraphrase is invisible and is the range review's to catch.

Measured example: ledger value 30 → 20, chapter prose says 三十五文 and never
names the owner — the chapter carried, and `audit` still reported ok. The
Chinese-numeral form is now generated by `_value_forms`, which closes that
instance; the class is closed only by the review net below, not by detection.

Detectors, each of which may independently refuse a carry:

  0. implicated chapters — a chapter named by the revision's own findings
     (target_chapter or evidence) is never carried: the fix verdict placed
     it under repair, so it must re-execute;
  1. declared dependencies — every chapter named in `plan['dependencies']`
     must be byte-identical between parent and branch;
  2. declared reads — the chapter's own `reads` list must not intersect the
     changed coordinates. This is the only detector that can see a
     description-style reference, because it is the only one the writer
     supplies rather than the engine guessing;
  3. dependency delta — the changed state keys must be disjoint from the
     chapter's read-set (plan entities + entities named in prose);
  4. surface sweep — literal forms of the old/new values, their Chinese
     numeric spelling, and the owning entities' names must not appear in the
     chapter's prose;
  5. echo sweep — for every upstream chapter whose prose changed between
     parent and branch, the removed literal segments must not appear in the
     chapter's prose (closes "another chapter still writes the old wording",
     including on an empty delta);
  6. replay — the chapter's own events must re-apply against the new branch
     prefix, and the parent's stored review verdicts must actually have passed.

The net that actually closes the class: carried chapters stay inside the
revision range, the chunked and range revision reviews still cover them, and
the range payload lists `carried_chapters` with a spot-check instruction.
Carried chapters keep their parent verdicts (marked carried_from) and are
surfaced in `status` and in book.html, because a chapter that skipped
per-chapter independent review must be visible to the author.
"""
import copy
import difflib
import json
from .store import Error, digest, dump, get, head, log, transaction
from .ledger import append_events, replay
from .settlement import semantic

# Collections whose change cannot be entity-scoped: any edit there blocks
# carry (v1 stays conservative; spatial facts ripple in ways the read-set
# does not encode).
UNSCOPABLE = frozenset(('entities', 'anchors', 'places', 'links', 'placements',
                        'hooks', 'developments', 'relations'))


def _entity_of(collection, key):
    """Owning entity ids of a state key, or None when unscopable."""
    if collection in ('facts', 'knowledge'):
        return {key.split(':', 1)[0]} if ':' in key else None
    if collection == 'resources':
        try:
            parsed = json.loads(key)
            return {parsed[0]} if isinstance(parsed, list) and parsed else None
        except ValueError:
            return None
    return None


def state_delta(before_state, after_state):
    """Semantic key-level delta between two replayed states."""
    before, after = semantic(before_state), semantic(after_state)
    delta = {}
    for collection in set(before) | set(after):
        old, new = before.get(collection) or {}, after.get(collection) or {}
        if not isinstance(old, dict) or not isinstance(new, dict):
            continue
        for key in set(old) | set(new):
            if old.get(key) != new.get(key):
                delta.setdefault(collection, {})[key] = (old.get(key), new.get(key))
    return delta


def _delta_entities(delta):
    ids = set()
    for collection, entries in delta.items():
        if collection in UNSCOPABLE:
            return None  # signal: unscopable change, deny carry
        for key in entries:
            owners = _entity_of(collection, key)
            if owners is None:
                return None
            ids |= owners
    return ids


def _read_set(db, branch, parent, n, prose, entities_index):
    """Same read-set review_context_hash binds: plan entities plus every
    entity named or aliased in the chapter prose. The branch's regenerated
    plan wins when present; the parent's is the carried chapter's origin."""
    ids = set()
    plan_row = db.execute('SELECT data FROM plans WHERE branch=? AND number=?', (branch, n)).fetchone()
    if plan_row is None:
        plan_row = db.execute('SELECT data FROM plans WHERE branch=? AND number=?', (parent, n)).fetchone()
    if plan_row:
        plan = json.loads(plan_row[0])
        ids.update(plan.get('entities', []))
        ids.update(choice.get('entity') for choice in plan.get('character_choices', []))
        for scene in plan.get('scenes', []):
            ids.update(scene.get('present', []))
            ids.update(scene.get('speakers', []))
            ids.update(scene.get('props', []))
            for intent in scene.get('dialogue_intents', []):
                if isinstance(intent, dict):
                    ids.add(intent.get('entity'))
                    if intent.get('to'):
                        ids.add(intent['to'])
    ids.discard(None)
    for eid, entity in entities_index.items():
        if any(name in prose for name in [entity.get('name', '')] + entity.get('aliases', [])):
            ids.add(eid)
    return ids


_DIGITS = '零一二三四五六七八九'
_UNITS = ('', '十', '百', '千')


def _chinese_number(value):
    """Chinese surface form of an integer. A ledger value stored as '30' is
    still recognisable when the prose writes 三十 or 三十五."""
    if value < 0:
        return '负' + _chinese_number(-value)
    if value == 0:
        return '零'
    if value >= 10000:
        high, low = divmod(value, 10000)
        return _chinese_number(high) + '万' + (_chinese_number(low) if low else '')
    digits = str(value)
    out = ''
    for index, char in enumerate(digits):
        digit = int(char)
        if digit == 0:
            if out and not out.endswith('零'):
                out += '零'
        else:
            out += _DIGITS[digit] + _UNITS[len(digits) - index - 1]
    return out.rstrip('零') or '零'


def _value_forms(value):
    """Surface forms a changed value may take in prose.

    P3 honest capability: this is a conservative approximation, never a proof.
    Matching stays literal, so a paraphrase, a pronoun or an unregistered
    reference is invisible here and is left to the revision range review.
    """
    if value is None:
        return set()
    if isinstance(value, bool):
        return {dump(value)}
    if isinstance(value, int):
        chinese = _chinese_number(value)
        # 十 is written both as 一十 and 十; accept either.
        return {str(value), chinese, chinese.replace('一十', '十', 1)}
    if isinstance(value, float):
        return {str(value)}
    if isinstance(value, str):
        forms = {value}
        if value.isdigit():
            forms.add(_chinese_number(int(value)))
        else:
            stripped = value.replace('零', '')
            if stripped and all(char in _DIGITS for char in stripped) and len(value) <= 8:
                forms.add(str(value))
        return forms
    return {dump(value)}


def _sweep_forms(delta, entities_index):
    """Literal surface forms of every changed value and owning entity name."""
    forms = set()
    for collection, entries in delta.items():
        for key, (old, new) in entries.items():
            for eid in _entity_of(collection, key) or set():
                entity = entities_index.get(eid)
                if entity:
                    forms.update({entity.get('name', ''), *entity.get('aliases', [])})
            for value in (old, new):
                forms |= _value_forms(value)
    # Single-character values are kept on purpose. The previous `len(text) >= 2`
    # floor silently dropped them, so a one-character ledger value (甲乙丙 ranks,
    # 密号, 方位, 字号 — ordinary shapes in Chinese) rode through whenever its
    # owning entity was unnamed in the prose. Over-refusing a carry costs one
    # re-drafted chapter; under-refusing costs a wrong canon.
    return {form for form in forms if form}


def _declared_dependency_changed(db, branch, parent, n):
    """True when a chapter this one declares as a dependency was rewritten.

    `plan['dependencies']` is the only explicit read declaration the kernel
    keeps, and the dependency delta never consulted it — so a chapter whose
    declared source changed upstream could still be carried on the strength of
    an entity read-set that does not encode prose dependencies at all.
    """
    row = db.execute('SELECT data FROM plans WHERE branch=? AND number=?', (branch, n)).fetchone()
    if row is None:
        row = db.execute('SELECT data FROM plans WHERE branch=? AND number=?', (parent, n)).fetchone()
    if row is None:
        return True                      # no plan: nothing to reason from
    for dep in json.loads(row[0]).get('dependencies') or []:
        if type(dep) is not int:
            return True                  # unknown shape: refuse rather than guess
        here = db.execute('SELECT hash FROM chapters WHERE branch=? AND number=?',
                          (branch, dep)).fetchone()
        there = db.execute('SELECT hash FROM chapters WHERE branch=? AND number=?',
                           (parent, dep)).fetchone()
        if (here[0] if here else None) != (there[0] if there else None):
            return True
    return False


def _changed_keys(delta):
    """Coordinates the revision changed, in the same `entity:key` string form a
    writer declares reads in."""
    return {key for collection in ('facts', 'knowledge') for key in (delta.get(collection) or {})}


def _declared_reads(db, branch, parent, n):
    """The chapter's own declaration of which ledger coordinates it read.

    Accepting a declaration can only narrow the carry set, never widen it, so an
    incomplete one is safe and an absent one keeps the previous behaviour. This
    is the only channel through which a chapter that refers to a value by
    description ("那把柴刀") can state the dependency at all — entity names and
    literal values cannot express it.
    """
    for source in (branch, parent):
        row = db.execute('SELECT data FROM chapters WHERE branch=? AND number=?',
                         (source, n)).fetchone()
        if row is None:
            continue
        reads = json.loads(row[0]).get('reads')
        if isinstance(reads, list):
            return {item for item in reads if isinstance(item, str)}
    return set()


def carried_chapters(db, branch):
    rows = db.execute('SELECT number,data FROM chapters WHERE branch=? ORDER BY number', (branch,)).fetchall()
    out = []
    for row in rows:
        try:
            data = json.loads(row['data'])
        except ValueError:
            continue
        if isinstance(data, dict) and data.get('carried_from'):
            out.append(row['number'])
    return out


def implicated_chapters(db, branch):
    """Chapters the revision's own findings placed under repair.

    The branch reason carries the fix verdict's findings: `target_chapter`
    names the repair site, and a finding's `evidence` chapter is quoted by
    the verdict and owed a spot-check. Either way the chapter must re-execute
    on this branch — carrying it verbatim would ship the very defect the
    revision exists to fix. Author-side `revise` passes a free-text reason;
    it names no chapters, so nothing is implicated.
    """
    row = db.execute('SELECT reason FROM branches WHERE id=?', (branch,)).fetchone()
    try:
        findings = json.loads(row['reason']) if row and row['reason'] else None
    except ValueError:
        return set()
    if not isinstance(findings, list):
        return set()
    out = set()
    for finding in findings:
        if not isinstance(finding, dict) or finding.get('severity') not in ('blocker', 'quality'):
            continue
        if type(finding.get('target_chapter')) is int:
            out.add(finding['target_chapter'])
        ref = finding.get('evidence')
        if isinstance(ref, dict) and type(ref.get('chapter')) is int:
            out.add(ref['chapter'])
    return out


def _removed_wordings(db, branch, parent, upto):
    """Literal segments the revision deleted from upstream prose.

    For every chapter below `upto` whose prose changed between parent and
    branch, collect the removed runs (difflib gaps in the old text). This is
    the only prose-level view an empty-delta carry gets: the ledger delta is
    empty exactly when the fix re-worded text, and a downstream chapter that
    still contains the removed wording — the measured multi-site glyph case —
    must not ride through on it.
    """
    forms = set()
    for row in db.execute(
            '''SELECT c.number AS number, p.prose AS old, c.prose AS new
               FROM chapters c JOIN chapters p ON p.branch=? AND p.number=c.number
               WHERE c.branch=? AND c.number<? AND c.hash!=p.hash''',
            (parent, branch, upto)):
        for tag, i1, i2, _j1, _j2 in difflib.SequenceMatcher(
                None, row['old'], row['new']).get_opcodes():
            if tag in ('delete', 'replace'):
                segment = row['old'][i1:i2].strip()
                if len(segment) >= 2:
                    forms.add(segment)
    return forms


def _carry_one(db, branch, parent, n, chapter_row):
    prose = chapter_row['prose']
    data = json.loads(chapter_row['data'])
    events = data.get('events')
    # A carried chapter must carry a finished review too: committed chapters
    # store both receipts; guard anyway so a malformed row cannot slip through.
    if not isinstance(events, list) or not isinstance(data.get('facts_review'), dict) or not isinstance(data.get('reader_review'), dict):
        return None
    try:
        parent_state = replay(db, parent, through=n - 1)
        branch_state = replay(db, branch)
        delta = state_delta(parent_state, branch_state)
        entities_index = branch_state.get('entities', {})
    except Error:
        # P4: carrying is an optimisation. A broken event chain is a real
        # finding, but it belongs to `audit` and to the normal dispatch that
        # follows — letting it escape here turned a recoverable integrity
        # problem into a hard dispatch failure.
        return None
    # An empty delta (expression-level fix, no ledger change) carries: every
    # value-based detector is vacuous precisely because no coordinate moved.
    # The wording that DID move is checked below by the echo sweep — the old
    # refusal here pushed the whole suffix into worker re-drafts, and the
    # re-drafts' own drift became the next review's findings.
    for verdict in (data.get('facts_review', {}).get('verdict'), data.get('reader_review', {}).get('verdict')):
        if verdict != 'pass':
            return None  # the verdict being carried must actually have passed
    changed = _delta_entities(delta)
    if changed is None:
        return None
    if _declared_dependency_changed(db, branch, parent, n):
        return None
    if _declared_reads(db, branch, parent, n) & _changed_keys(delta):
        return None
    if changed & _read_set(db, branch, parent, n, prose, entities_index):
        return None
    forms = _sweep_forms(delta, entities_index)
    if forms and any(form in prose for form in forms):
        return None
    echoes = _removed_wordings(db, branch, parent, n)
    if echoes and any(segment in prose for segment in echoes):
        return None
    stored = copy.deepcopy(data)
    stored['carried_from'] = parent
    stored['carried_delta'] = bool(delta)
    try:
        with transaction(db):
            db.execute('INSERT INTO chapters VALUES (?,?,?,?,?)', (branch, n, prose, dump(stored), digest(prose)))
            append_events(db, branch, n, prose, events, branch_state)
            from .engine import validate_hook_deadlines
            validate_hook_deadlines(branch_state, n)
            db.execute('INSERT OR IGNORE INTO plans SELECT ?,number,data FROM plans WHERE branch=? AND number=?', (branch, parent, n))
            log(db, 'revision_carry', {'branch': branch, 'chapter': n, 'from': parent,
                                       'delta_touched': bool(delta)})
    except Exception:
        return None  # replay or uniqueness refused the carry: normal dispatch follows
    return n


def fast_forward(db, branch):
    """Carry the provably-unaffected suffix; returns chapters carried now."""
    rev = db.execute('SELECT * FROM branches WHERE id=?', (branch,)).fetchone()
    if not rev or rev['status'] != 'candidate':
        return []
    if get(db, 'style_only_branch') == branch:
        # A style-only revision re-words every chapter; carrying any of them
        # verbatim would ship exactly the style inconsistency it exists to fix.
        return []
    if db.execute("SELECT 1 FROM tasks WHERE state='pending'").fetchone() or get(db, 'status') != 'ready':
        return []
    if head(db, branch) < rev['start']:
        # Nothing in the revision range has landed yet: an empty delta here
        # means "the fix has not happened", not "the chapter is unaffected".
        return []
    parent = rev['parent']
    implicated = implicated_chapters(db, branch)
    from .engine import load_draft
    carried = []
    while True:
        n = head(db, branch) + 1
        if n > rev['through']:
            break
        if n in implicated:
            break  # the findings named this chapter: it re-executes, never carries
        if load_draft(db, branch, n):
            break  # a worker already holds this chapter; normal flow continues
        chapter = db.execute('SELECT * FROM chapters WHERE branch=? AND number=?', (parent, n)).fetchone()
        if chapter is None or _carry_one(db, branch, parent, n, chapter) is None:
            break
        carried.append(n)
    return carried
